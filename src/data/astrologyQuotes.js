/**
 * Select a quote prioritizing the user's star sign quotes and avoiding repeats.
 * Initial call (no excludeText) returns a sign-specific quote whenever signId is valid.
 */
export function getAstrologyQuote(signId, excludeText = null) {
  const normalizedSignId =
    typeof signId === "string" ? signId.toLowerCase() : null;
  const signPool =
    normalizedSignId && SIGN_QUOTES[normalizedSignId]
      ? SIGN_QUOTES[normalizedSignId]
      : null;

  const chooseFromPool = (pool) => {
    const filtered =
      excludeText && pool.length > 1
        ? pool.filter((q) => q !== excludeText)
        : pool;
    const index = Math.floor(Math.random() * filtered.length);
    return filtered[index];
  };

  if (!signPool) {
    return {
      text: chooseFromPool(GENERAL_ASTROLOGY_QUOTES),
      signId: null,
      isSignSpecific: false,
    };
  }

  // Initial selection always prioritizes the user's sign; subsequent refreshes mix ~75% sign / ~25% general.
  const useSignSpecific = excludeText == null ? true : Math.random() < 0.75;

  if (useSignSpecific) {
    return {
      text: chooseFromPool(signPool),
      signId: normalizedSignId,
      isSignSpecific: true,
    };
  }

  return {
    text: chooseFromPool(GENERAL_ASTROLOGY_QUOTES),
    signId: normalizedSignId,
    isSignSpecific: false,
  };
}
